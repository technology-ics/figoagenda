const ROLE_KEYS = {
  moderator: "roleModerator",
  speaker: "roleSpeaker",
  panelist: "rolePanelist",
};

const LANGUAGE_KEYS = {
  english: "langEnglish",
  french: "langFrench",
  spanish: "langSpanish",
};

export function translate(language, key, vars) {
  const dictionary = translations[language] || translations["en-GB"];
  let text = dictionary[key] ?? translations["en-GB"][key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function translateRole(role, language) {
  const key = ROLE_KEYS[String(role || "").trim().toLowerCase()];
  return key ? translate(language, key) : String(role || "").trim();
}

export function translateSessionLanguage(value, language) {
  const key = LANGUAGE_KEYS[String(value || "").trim().toLowerCase()];
  return key ? translate(language, key) : String(value || "").trim();
}

/** Scientific field in the selected language, or the original source text when no approved translation exists. */
export function localContent(entry, language) {
  if (!entry) return "";
  if (typeof entry === "string") return entry;
  const specific = entry[language];
  if (specific && String(specific).trim()) return String(specific).trim();
  return String(entry.source || "").trim();
}
